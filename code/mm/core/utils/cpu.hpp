constexpr int map_thread_id_to_core_id(int thread_id)
{
    if ((thread_id & 1) == 0) // even
    {
        return thread_id >> 1; // div by 2
    }
    else
    {
        return 16 + (thread_id >> 1); // div by 2 and add 16
    }
}

static_assert(map_thread_id_to_core_id(0) == 0);
static_assert(map_thread_id_to_core_id(1) == 16);
static_assert(map_thread_id_to_core_id(2) == 1);
static_assert(map_thread_id_to_core_id(3) == 17);
static_assert(map_thread_id_to_core_id(4) == 2);
static_assert(map_thread_id_to_core_id(5) == 18);
static_assert(map_thread_id_to_core_id(6) == 3);
static_assert(map_thread_id_to_core_id(7) == 19);
static_assert(map_thread_id_to_core_id(8) == 4);
static_assert(map_thread_id_to_core_id(9) == 20);

